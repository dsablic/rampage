/// Whether `path` (repository-relative, `/`-separated) is one `allowlist` admits.
pub fn allowed(path: &str, allowlist: &[&str]) -> bool {
    if path.is_empty() || path.starts_with('/') || path.split('/').any(|part| part == ".." || part == ".") {
        return false;
    }
    allowlist.iter().any(|entry| match entry.strip_suffix('/') {
        Some(directory) => path.strip_prefix(directory).is_some_and(|rest| rest.starts_with('/') && rest.len() > 1),
        None => path == *entry,
    })
}

/// Lexical markers an added line of the change may not contain. The matcher works from the binary and the
/// compiled-in databases; this check is advisory, a tripwire on top of the sandbox (which is what keeps the build,
/// the tests and identification from reading what they may not). It is conservative: a comment mentioning one of
/// them fails too.
const FORBIDDEN: &[&str] = &[
    "std::fs",
    "std::env",
    "std::process",
    "std::net",
    "std::os",
    "std::io::stdin",
    "File::",
    "OpenOptions",
    "read_dir",
    "include_bytes!",
    "include_str!",
    "include!",
    "env!",
    "option_env!",
    "unsafe",
    "extern ",
    "#[link",
    "#[path",
    "#![",
    "Command::",
    "TcpStream",
    "UdpSocket",
    "UnixStream",
    "libc::",
    "rustix::",
    "asm!",
    "proc_macro",
];

/// Modules that are I/O when named after `::` or in a `use` group (`use std::{fs, io}`).
const FORBIDDEN_MODULES: &[&str] = &["fs", "env", "process", "net", "os"];

/// `line` with whitespace runs collapsed to one space and dropped around `:`, `!`, `#`, `[`, `(` and `{`, so
/// `std :: fs` or `include_str !(` read as their markers.
fn normalised(line: &str) -> String {
    let collapsed = line.split_whitespace().collect::<Vec<_>>().join(" ");
    let glue = [':', '!', '#', '[', '(', '{'];
    let characters: Vec<char> = collapsed.chars().collect();
    let mut out = String::with_capacity(characters.len());
    for (index, &character) in characters.iter().enumerate() {
        if character == ' ' {
            let before = index.checked_sub(1).map(|at| characters[at]);
            let after = characters.get(index + 1).copied();
            if before.is_some_and(|c| glue.contains(&c)) || after.is_some_and(|c| glue.contains(&c)) {
                continue;
            }
        }
        out.push(character);
    }
    out
}

/// The marker `line` holds, if any.
pub fn forbidden(line: &str) -> Option<String> {
    let line = normalised(line);
    if let Some(marker) = FORBIDDEN.iter().find(|marker| line.contains(*marker)) {
        return Some((*marker).to_owned());
    }
    let words: Vec<&str> =
        line.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == ':')).filter(|w| !w.is_empty()).collect();
    for word in &words {
        for module in FORBIDDEN_MODULES {
            if *word == *module && line.contains("use ") && line.contains('{') {
                return Some(format!("{module} in a use group"));
            }
            let parts: Vec<&str> = word.split("::").collect();
            if parts.len() > 1 && parts[..parts.len() - 1].contains(module) {
                return Some(format!("{module}::"));
            }
        }
    }
    None
}

/// Whether an added line is mostly literal data: at least four numeric or string literals and at most half as many
/// other identifiers, or one string literal over 64 characters. Long runs of such lines are how a table of names or
/// hashes would be smuggled into source.
pub fn literal_line(line: &str) -> bool {
    let mut literals = 0;
    let mut identifiers = 0;
    let mut characters = line.trim().chars().peekable();
    while let Some(character) = characters.next() {
        if character == '"' {
            let mut length = 0;
            let mut escaped = false;
            for inner in characters.by_ref() {
                if escaped {
                    escaped = false;
                } else if inner == '\\' {
                    escaped = true;
                } else if inner == '"' {
                    break;
                }
                length += 1;
            }
            if length > 64 {
                return true;
            }
            literals += 1;
        } else if character.is_ascii_digit() {
            while characters.peek().is_some_and(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '.') {
                characters.next();
            }
            literals += 1;
        } else if character.is_ascii_alphabetic() || character == '_' {
            while characters.peek().is_some_and(|c| c.is_ascii_alphanumeric() || *c == '_') {
                characters.next();
            }
            identifiers += 1;
        } else if character == '/' && characters.peek() == Some(&'/') {
            break;
        }
    }
    literals >= 4 && identifiers * 2 <= literals
}

/// Size limits on a change: added lines in all, and added lines that are mostly literal data.
#[derive(Debug, Clone, Copy)]
pub struct Limits {
    pub max_added_lines: usize,
    pub max_literal_lines: usize,
}

impl Default for Limits {
    fn default() -> Limits {
        Limits { max_added_lines: 800, max_literal_lines: 40 }
    }
}

/// A change read back from the session's tree: every path that differs from the base, the ones that are not plain
/// files, and the binary patch of the allowlisted ones as the harness's own tree holds them.
#[derive(Debug, Clone, Default)]
pub struct Diff {
    pub patch: String,
    pub paths: Vec<String>,
    /// Paths that are symlinks, other non-regular files, or changed only their executable bit.
    pub special: Vec<String>,
}

impl Diff {
    pub fn is_empty(&self) -> bool {
        self.paths.is_empty()
    }

    pub fn sha256(&self) -> String {
        rampage_arch::hex::bytes(&Sha256::digest(self.patch.as_bytes()))
    }

    /// Lines added and removed, as `git diff --stat` counts text lines.
    pub fn line_counts(&self) -> (usize, usize) {
        let mut counts = (0, 0);
        for line in self.patch.lines() {
            if line.starts_with("+++") || line.starts_with("---") {
                continue;
            }
            if line.starts_with('+') {
                counts.0 += 1;
            } else if line.starts_with('-') {
                counts.1 += 1;
            }
        }
        counts
    }
}

/// Every reason `diff` is refused: a path outside the allowlist, a special file, a mode change or binary file, an
/// added line with a [`forbidden`] marker, or more added lines (or literal lines) than `limits` allow.
pub fn policy_violations(diff: &Diff, allowlist: &[&str], limits: Limits) -> Vec<String> {
    let mut violations = Vec::new();
    for path in &diff.paths {
        if !allowed(path, allowlist) {
            violations.push(format!("{path}: outside the allowlist"));
        }
    }
    for path in &diff.special {
        violations.push(format!("{path}: not a plain file, or its mode changed"));
    }
    let mut current = String::new();
    let (mut added, mut literal) = (0, 0);
    for line in diff.patch.lines() {
        if let Some(header) = line.strip_prefix("diff --git ") {
            current = match header.strip_prefix("a/").and_then(|rest| rest.split_once(" b/")) {
                Some((_, after)) => after.to_owned(),
                None => {
                    violations.push(format!("unusual path in `{line}`"));
                    header.to_owned()
                }
            };
            continue;
        }
        let mode = ["new file mode ", "deleted file mode ", "old mode ", "new mode "]
            .iter()
            .find_map(|prefix| line.strip_prefix(prefix));
        if let Some(mode) = mode {
            if line.starts_with("old mode ") || line.starts_with("new mode ") {
                violations.push(format!("{current}: file mode change"));
            } else if mode != "100644" {
                violations.push(format!("{current}: file mode {mode} (only plain files)"));
            }
            continue;
        }
        if line == "GIT binary patch" || line.starts_with("Binary files ") {
            violations.push(format!("{current}: binary file"));
            continue;
        }
        if let Some(text) = line.strip_prefix('+')
            && !line.starts_with("+++")
        {
            added += 1;
            if literal_line(text) {
                literal += 1;
            }
            if let Some(marker) = forbidden(text) {
                violations.push(format!("{current}: added line uses `{marker}`: {}", text.trim()));
            }
        }
    }
    if added > limits.max_added_lines {
        violations.push(format!("{added} added lines (at most {})", limits.max_added_lines));
    }
    if literal > limits.max_literal_lines {
        violations.push(format!(
            "{literal} added lines are mostly literal data (at most {}); data derived from training belongs in the \
             generated heuristics file",
            limits.max_literal_lines
        ));
    }
    violations.sort();
    violations.dedup();
    violations
}

/// Runs a command and returns its standard output, or an error with its standard error.
pub fn output(command: &mut Command) -> Result<String, String> {
    let shown = format!("{command:?}");
    let output = command.output().map_err(|error| format!("{shown}: {error}"))?;
    if !output.status.success() {
        return Err(format!("{shown}: {}: {}", output.status, String::from_utf8_lossy(&output.stderr).trim()));
    }
    String::from_utf8(output.stdout).map_err(|error| format!("{shown}: {error}"))
}

/// A repository or worktree the harness runs git in, with its git directory and work tree given explicitly as
/// recorded when the harness made them, never discovered through a `.git` file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Repo {
    pub git_dir: PathBuf,
    pub work_tree: Option<PathBuf>,
}

impl Repo {
    /// git with no global or system configuration, no hooks, no fsmonitor, no external diff or textconv, and the
    /// recorded directories: a configuration file, hook or `.git` file the agent wrote changes nothing it runs.
    pub fn git(&self) -> Command {
        let mut command = Command::new("git");
        for variable in ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR", "GIT_CONFIG", "GIT_EXEC_PATH"]
        {
            command.env_remove(variable);
        }
        command
            .env("GIT_CONFIG_GLOBAL", "/dev/null")
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .env("GIT_TERMINAL_PROMPT", "0")
            .env("GIT_DIR", &self.git_dir)
            .args(["-c", "core.fsmonitor=", "-c", "core.hooksPath=/dev/null", "-c", "core.untrackedCache=false"])
            .args(["-c", "diff.external=", "-c", "core.pager=cat", "-c", "protocol.allow=never"]);
        match &self.work_tree {
            Some(tree) => {
                command.env("GIT_WORK_TREE", tree).current_dir(tree);
            }
            None => {
                command.current_dir(&self.git_dir);
            }
        }
        command
    }

    /// The full commit id `revision` names.
    pub fn resolve(&self, revision: &str) -> Result<String, String> {
        Ok(output(self.git().args(["rev-parse", "--verify", &format!("{revision}^{{commit}}")]))?.trim().to_owned())
    }
}

/// The repository the harness was started in: its common git directory, read once from the operator's checkout.
pub fn operator_repo(checkout: &Path) -> Result<(Repo, PathBuf), String> {
    let mut command = Command::new("git");
    command.env("GIT_CONFIG_GLOBAL", "/dev/null").env("GIT_CONFIG_NOSYSTEM", "1").arg("-C").arg(checkout);
    let common = output(command.args(["rev-parse", "--path-format=absolute", "--git-common-dir", "--show-toplevel"]))?;
    let mut lines = common.lines();
    let git_dir = crate::flywheel_code_sandbox::canonical(Path::new(lines.next().unwrap_or_default().trim()));
    let top = crate::flywheel_code_sandbox::canonical(Path::new(lines.next().unwrap_or_default().trim()));
    Ok((Repo { git_dir, work_tree: None }, top))
}

/// A detached worktree of `repo` at `commit` in `path` (which must not exist), returned with its recorded git
/// directory (read from the `.git` file git just wrote, before anything else could).
pub fn add_worktree(repo: &Repo, path: &Path, commit: &str) -> Result<Repo, String> {
    output(repo.git().args(["worktree", "add", "--detach"]).arg(path).arg(commit))?;
    let pointer = std::fs::read_to_string(path.join(".git")).map_err(|error| format!("{}: {error}", path.display()))?;
    let git_dir = PathBuf::from(pointer.trim().strip_prefix("gitdir: ").ok_or("unexpected .git file")?);
    if !git_dir.starts_with(&repo.git_dir) {
        return Err(format!("{}: worktree git directory {} outside the repository", path.display(), git_dir.display()));
    }
    Ok(Repo { git_dir, work_tree: Some(path.to_path_buf()) })
}

/// Removes a worktree made by [`add_worktree`], with whatever it holds.
pub fn remove_worktree(repo: &Repo, path: &Path) -> Result<(), String> {
    if path.exists() {
        output(repo.git().args(["worktree", "remove", "--force"]).arg(path))?;
    }
    output(repo.git().args(["worktree", "prune"])).map(|_| ())
}

/// Resets `worktree` to `base` exactly and applies `diff`'s patch (nothing when it is empty).
pub fn apply_diff(worktree: &Repo, base: &str, diff: &Diff, patch_file: &Path) -> Result<(), String> {
    output(worktree.git().args(["reset", "--quiet", "--hard", base]))?;
    output(worktree.git().args(["clean", "-q", "-ffdx"]))?;
    if diff.patch.is_empty() {
        return Ok(());
    }
    std::fs::write(patch_file, &diff.patch).map_err(|error| format!("{}: {error}", patch_file.display()))?;
    output(worktree.git().args(["apply", "--binary", "--whitespace=nowarn"]).arg(patch_file)).map(|_| ())
}

/// Writes `base`'s tree into `destination` (which must not exist) with `excluded` paths removed: an export with no
/// tie to the repository, for the session and as the harness's reference copy.
pub fn export_tree(repo: &Repo, base: &str, destination: &Path, excluded: &[&str]) -> Result<(), String> {
    std::fs::create_dir_all(destination).map_err(|error| format!("{}: {error}", destination.display()))?;
    let archive = destination.with_extension("tar");
    output(repo.git().args(["archive", "--format=tar", "-o"]).arg(&archive).arg(base))?;
    let extracted = output(Command::new("tar").arg("-xf").arg(&archive).arg("-C").arg(destination));
    let _ = std::fs::remove_file(&archive);
    extracted?;
    for path in excluded {
        let target = destination.join(path);
        if target.is_dir() {
            std::fs::remove_dir_all(&target).map_err(|error| format!("{}: {error}", target.display()))?;
        } else if target.exists() {
            std::fs::remove_file(&target).map_err(|error| format!("{}: {error}", target.display()))?;
        }
    }
    Ok(())
}

/// One file's state in a tree: its bytes and whether it is executable, or that it is not a plain file.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Entry {
    File { executable: bool, digest: [u8; 32] },
    Special,
}

/// Every file under `root` by relative path, without following symlinks, leaving out the top-level `skip` names.
fn walk(root: &Path, skip: &[&str]) -> Result<BTreeMap<String, Entry>, String> {
    use std::os::unix::fs::PermissionsExt;
    let mut entries = BTreeMap::new();
    let mut pending = vec![PathBuf::new()];
    while let Some(relative) = pending.pop() {
        let directory = root.join(&relative);
        let listing = std::fs::read_dir(&directory).map_err(|error| format!("{}: {error}", directory.display()))?;
        for item in listing {
            let item = item.map_err(|error| error.to_string())?;
            let name = item.file_name().to_string_lossy().into_owned();
            if relative.as_os_str().is_empty() && skip.contains(&name.as_str()) {
                continue;
            }
            let path = relative.join(&name);
            let key = path.to_string_lossy().into_owned();
            let metadata = std::fs::symlink_metadata(item.path()).map_err(|error| error.to_string())?;
            if metadata.is_dir() {
                pending.push(path);
            } else if metadata.is_file() {
                let bytes = std::fs::read(item.path()).map_err(|error| format!("{key}: {error}"))?;
                let executable = metadata.permissions().mode() & 0o111 != 0;
                entries.insert(key, Entry::File { executable, digest: Sha256::digest(&bytes).into() });
            } else {
                entries.insert(key, Entry::Special);
            }
        }
    }
    Ok(entries)
}

/// What changed in `session` against the harness's reference export `reference`: changed paths (added, modified or
/// deleted), and those that are special. Read with plain file operations; nothing runs in the session's tree. Its
/// top-level `.git` (the session's own history) and the generated heuristics file are left out.
pub fn read_changes(session: &Path, reference: &Path) -> Result<(Vec<String>, Vec<String>), String> {
    let skip = [".git"];
    let (now, before) = (walk(session, &skip)?, walk(reference, &skip)?);
    let mut changed = BTreeSet::new();
    let mut special = BTreeSet::new();
    for (path, entry) in &now {
        if path == GENERATED {
            continue;
        }
        match (entry, before.get(path)) {
            (Entry::Special, _) => {
                changed.insert(path.clone());
                special.insert(path.clone());
            }
            (Entry::File { executable, digest }, Some(Entry::File { executable: was, digest: had })) => {
                if digest != had || executable != was {
                    changed.insert(path.clone());
                }
                if executable != was {
                    special.insert(path.clone());
                }
            }
            (Entry::File { executable, .. }, _) => {
                changed.insert(path.clone());
                if *executable {
                    special.insert(path.clone());
                }
            }
        }
    }
    for path in before.keys() {
        if !now.contains_key(path) && path != GENERATED {
            changed.insert(path.clone());
        }
    }
    Ok((changed.into_iter().collect(), special.into_iter().collect()))
}

/// The change in `session` as a [`Diff`]: the allowlisted plain files are copied into the harness's worktree `gate`
/// (reset to `base` first) and diffed there by the harness's git; other changed paths are only listed, never copied.
pub fn capture(session: &Path, reference: &Path, gate: &Repo, base: &str, allowlist: &[&str]) -> Result<Diff, String> {
    let (paths, special) = read_changes(session, reference)?;
    let tree = gate.work_tree.clone().ok_or("the gate repository has no work tree")?;
    output(gate.git().args(["reset", "--quiet", "--hard", base]))?;
    output(gate.git().args(["clean", "-q", "-ffdx"]))?;
    for path in paths.iter().filter(|path| allowed(path, allowlist) && !special.contains(path)) {
        let (from, to) = (session.join(path), tree.join(path));
        if from.is_file() {
            if let Some(parent) = to.parent() {
                std::fs::create_dir_all(parent).map_err(|error| format!("{}: {error}", parent.display()))?;
            }
            std::fs::copy(&from, &to).map_err(|error| format!("{path}: {error}"))?;
        } else if to.exists() {
            std::fs::remove_file(&to).map_err(|error| format!("{path}: {error}"))?;
        }
    }
    output(gate.git().args(["add", "-A"]))?;
    let patch = output(gate.git().args(["diff", "--cached", "--binary", "--no-renames", "--full-index"]).args([
        "--no-ext-diff",
        "--no-textconv",
        base,
    ]))?;
    output(gate.git().args(["reset", "--quiet", "--hard", base]))?;
    Ok(Diff { patch, paths, special })
}

/// A corpus view: a directory with a manifest of only the binaries of `roles`, and copies (copy-on-write clones on
/// APFS) of only their files. With `truth` (the training split, whose truth the agent may read), each binary keeps
/// its id, its symbolized twin and its objects. Without, every binary gets a neutral id (`b0001`...), the role
/// `heldout` and no version, the twin entry points at the stripped binary and no object is copied: nothing in the view
/// says what a function is called or which split it is. Returns the neutral ids' real ids.
pub fn make_view(
    corpus: &Corpus,
    roles: &[Role],
    truth: bool,
    view: &Path,
) -> Result<BTreeMap<String, String>, String> {
    let mut binaries: Vec<CorpusBinary> = Vec::new();
    let mut files: Vec<(String, String)> = Vec::new();
    let mut ids = BTreeMap::new();
    for binary in corpus.manifest.binaries.iter().filter(|binary| roles.contains(&binary.split)) {
        let mut entry = binary.clone();
        if truth {
            for path in
                [Some(&entry.stripped), Some(&entry.twin), entry.program_object.as_ref(), entry.library_object.as_ref()]
                    .into_iter()
                    .flatten()
            {
                files.push((path.clone(), path.clone()));
            }
        } else {
            let id = format!("b{:04}", ids.len() + 1);
            ids.insert(id.clone(), entry.id.clone());
            let stripped = format!("bin/{id}.elf");
            files.push((entry.stripped.clone(), stripped.clone()));
            entry.id = id;
            entry.program = "-".to_owned();
            entry.library_version = "-".to_owned();
            entry.split = Role::Heldout;
            entry.stripped = stripped.clone();
            entry.twin = stripped;
            entry.twin_sha256 = entry.stripped_sha256.clone();
            entry.program_object = None;
            entry.program_object_sha256 = None;
            entry.library_object = None;
            entry.library_object_sha256 = None;
            entry.program_names = Vec::new();
        }
        binaries.push(entry);
    }
    if binaries.is_empty() {
        return Err(format!("the corpus has no binary in {roles:?}"));
    }
    std::fs::create_dir_all(view).map_err(|error| format!("{}: {error}", view.display()))?;
    let mut copied = BTreeSet::new();
    for (from, to) in &files {
        if !copied.insert(to.clone()) {
            continue;
        }
        let (from, to) = (corpus.path(from), view.join(to));
        if let Some(parent) = to.parent() {
            std::fs::create_dir_all(parent).map_err(|error| format!("{}: {error}", parent.display()))?;
        }
        if !to.is_file() {
            std::fs::copy(&from, &to).map_err(|error| format!("{} -> {}: {error}", from.display(), to.display()))?;
        }
    }
    let mut manifest = CorpusManifest { binaries, ..corpus.manifest.clone() };
    if !truth {
        manifest.split.final_split = String::new();
        manifest.libraries = Vec::new();
    }
    let text = serde_json::to_string_pretty(&manifest).map_err(|error| error.to_string())?;
    let path = view.join(rampage_api::flywheel::MANIFEST);
    std::fs::write(&path, text).map_err(|error| format!("{}: {error}", path.display()))?;
    Ok(ids)
}

/// The in-session gate client: submits a request into the spool the harness watches and waits for its answer.
pub fn gate_client(spool: &Path) -> String {
    let spool = spool.to_string_lossy().replace('\'', "'\\''");
    format!(
        r#"#!/bin/sh
# flywheel-gate: gate this worktree's change (build, rampage-signatures tests, training, negatives, dev verdict,
# slices, time). Prints the gate's JSON answer; exits 0 when every stage passes, 1 when one fails, 3 when it is still
# running after FLYWHEEL_GATE_WAIT seconds (then run `flywheel-gate --wait ID`).
set -eu
spool='{spool}'
if [ "${{1:-}}" = "--wait" ]; then
  id="${{2:?usage: flywheel-gate --wait ID}}"
else
  id="$(date +%s)-$$"
  printf '{{"id":"%s"}}\n' "$id" > "$spool/requests/.$id.tmp"
  mv "$spool/requests/.$id.tmp" "$spool/requests/$id.json"
  echo "gate request $id submitted; a gate takes several minutes" >&2
fi
waited=0
limit="${{FLYWHEEL_GATE_WAIT:-1500}}"
while [ ! -f "$spool/responses/$id.status" ]; do
  if [ "$waited" -ge "$limit" ]; then
    echo "gate $id is still running; run: flywheel-gate --wait $id" >&2
    exit 3
  fi
  sleep 5
  waited=$((waited + 5))
done
cat "$spool/responses/$id.json"
[ "$(cat "$spool/responses/$id.status")" = "pass" ]
"#
    )
}

