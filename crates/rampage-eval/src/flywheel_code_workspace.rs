    fn diff(patch: &str) -> Diff {
        let mut paths = Vec::new();
        for line in patch.lines() {
            if let Some((_, after)) = line.strip_prefix("diff --git a/").and_then(|rest| rest.split_once(" b/")) {
                paths.push(after.to_owned());
            }
        }
        Diff { patch: patch.to_owned(), paths, special: Vec::new() }
    }

    const FILE: &str = "diff --git a/crates/rampage-signatures/src/lib.rs b/crates/rampage-signatures/src/lib.rs\n";

    fn violations(patch: &str) -> Vec<String> {
        policy_violations(&diff(patch), LIBID_ALLOWLIST, Limits::default())
    }

