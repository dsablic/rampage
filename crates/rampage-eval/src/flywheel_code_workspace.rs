    fn scratch_repo(name: &str) -> (PathBuf, Repo, String) {
        let root = canonical(&std::env::temp_dir()).join(format!("rampage-code-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let checkout = root.join("repo");
        std::fs::create_dir_all(checkout.join("src")).unwrap();
        std::fs::create_dir_all(checkout.join("tools/flywheel")).unwrap();
        std::fs::write(checkout.join("src/lib.rs"), "fn a() {}\n").unwrap();
        std::fs::write(checkout.join("src/other.rs"), "fn o() {}\n").unwrap();
        std::fs::write(checkout.join("tools/flywheel/corpus.json"), "{\"final\": []}\n").unwrap();
        let run = |args: &[&str]| {
            output(
                Command::new("git")
                    .arg("-C")
                    .arg(&checkout)
                    .args(["-c", "user.name=t", "-c", "user.email=t@t"])
                    .args(args),
            )
            .unwrap()
        };
        run(&["init", "-q"]);
        run(&["add", "-A"]);
        run(&["commit", "-qm", "base"]);
        let (repo, _) = operator_repo(&checkout).unwrap();
        let base = repo.resolve("HEAD").unwrap();
        (root, repo, base)
    }

    /// The session's tree is an export without the corpus recipe; its changes are read with file operations and
    /// diffed in the harness's worktree; other paths are listed, never copied.
    #[test]
    #[cfg(unix)]
    fn changes_are_read_from_an_export_and_diffed_in_the_harness_tree() {
        let (root, repo, base) = scratch_repo("capture");
        let (session, reference) = (root.join("session"), root.join("reference"));
        export_tree(&repo, &base, &session, SESSION_EXCLUDED).unwrap();
        export_tree(&repo, &base, &reference, SESSION_EXCLUDED).unwrap();
        assert!(!session.join("tools/flywheel/corpus.json").exists(), "the corpus recipe reached the session");
        assert!(session.join("src/lib.rs").is_file() && !session.join(".git").exists());
        let gate = add_worktree(&repo, &root.join("gate"), &base).unwrap();
        let allow = &["src/lib.rs", "src/new/"];
        assert!(capture(&session, &reference, &gate, &base, allow).unwrap().is_empty());
        std::fs::write(session.join("src/lib.rs"), "fn a() {}\nfn b() {}\n").unwrap();
        std::fs::create_dir_all(session.join("src/new")).unwrap();
        std::fs::write(session.join("src/new/c.rs"), "fn c() {}\n").unwrap();
        std::fs::remove_file(session.join("src/other.rs")).unwrap();
        std::os::unix::fs::symlink("/etc/passwd", session.join("src/new/link.rs")).unwrap();
        std::fs::create_dir_all(session.join(".git")).unwrap();
        std::fs::write(session.join(".git/config"), "[core]\n\tfsmonitor = /bin/false\n").unwrap();
        let captured = capture(&session, &reference, &gate, &base, allow).unwrap();
        assert_eq!(captured.paths, ["src/lib.rs", "src/new/c.rs", "src/new/link.rs", "src/other.rs"]);
        assert_eq!(captured.special, ["src/new/link.rs"]);
        assert!(captured.patch.contains("+fn b() {}") && captured.patch.contains("+fn c() {}"), "{}", captured.patch);
        assert!(!captured.patch.contains("other.rs") && !captured.patch.contains("passwd"), "{}", captured.patch);
        let found = policy_violations(&captured, allow, Limits::default());
        assert_eq!(found.len(), 2, "{found:?}");
        // Applying it to a clean copy gives the allowlisted files, and an empty diff resets.
        apply_diff(&gate, &base, &captured, &root.join("change.patch")).unwrap();
        assert_eq!(std::fs::read_to_string(root.join("gate/src/new/c.rs")).unwrap(), "fn c() {}\n");
        apply_diff(&gate, &base, &Diff::default(), &root.join("change.patch")).unwrap();
        assert!(!root.join("gate/src/new/c.rs").exists());
        remove_worktree(&repo, &root.join("gate")).unwrap();
        std::fs::remove_dir_all(&root).unwrap();
    }

    /// The harness's git ignores a global configuration, hooks and fsmonitor the agent could have written: a hook
    /// that plain git would run never runs.
    #[test]
    #[cfg(unix)]
    fn git_fsmonitor_and_hooks_from_agent_writable_config_never_run() {
        use std::os::unix::fs::PermissionsExt;
        let (root, repo, base) = scratch_repo("fsmonitor");
        let home = root.join("home");
        std::fs::create_dir_all(&home).unwrap();
        let marker = root.join("hook-ran");
        let hook = root.join("hook.sh");
        std::fs::write(&hook, format!("#!/bin/sh\ntouch {}\nexit 1\n", marker.display())).unwrap();
        std::fs::set_permissions(&hook, std::fs::Permissions::from_mode(0o755)).unwrap();
        std::fs::write(
            home.join(".gitconfig"),
            format!("[core]\n\tfsmonitor = {}\n\thooksPath = {}\n", hook.display(), root.display()),
        )
        .unwrap();
        let gate = add_worktree(&repo, &root.join("gate"), &base).unwrap();
        // Plain git with that HOME runs the hook: the attack is real.
        let plain = Command::new("git").env("HOME", &home).arg("-C").arg(root.join("gate")).args(["status"]).output();
        assert!(plain.is_ok());
        assert!(marker.exists(), "plain git did not run the fsmonitor hook, so the test proves nothing");
        std::fs::remove_file(&marker).unwrap();
        // The harness's git with the same HOME, and a .git file the agent rewrote, does not.
        std::fs::write(root.join("gate/.git"), "gitdir: /nonexistent\n").unwrap();
        let mut status = gate.git();
        status.env("HOME", &home).args(["status", "--porcelain"]);
        output(&mut status).unwrap();
        let mut add = gate.git();
        add.env("HOME", &home).args(["add", "-A"]);
        output(&mut add).unwrap();
        assert!(!marker.exists(), "the harness's git ran the agent's hook");
        std::fs::write(root.join("gate/.git"), format!("gitdir: {}\n", gate.git_dir.display())).unwrap();
        remove_worktree(&repo, &root.join("gate")).unwrap();
        std::fs::remove_dir_all(&root).unwrap();
    }
